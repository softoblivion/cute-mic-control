static class Policy {
    internal static void SetDefault(string id,int role) { object p=new PolicyConfigClient(); try { Com.Check(((IPolicyConfig)p).SetDefaultEndpoint(id,role)); } finally { Com.Release(p); } }
    internal static void SetProperty(string id,PropertyKey key,PropVariant value) { object p=new PolicyConfigClient(); try { Com.Check(((IPolicyConfig)p).SetPropertyValue(id,0,ref key,ref value)); } finally { Com.Release(p); } }
}
