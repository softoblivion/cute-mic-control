}
[StructLayout(LayoutKind.Sequential)] struct PropertyKey { internal Guid Format; internal int Id; internal PropertyKey(Guid format,int id) { Format=format; Id=id; } }
// PROPVARIANT: vt, three reserved words, then the value union (8 bytes on x86, 16 on x64 through the two pointer fields),
// 16 bytes in all on x86 and 24 on x64.
[StructLayout(LayoutKind.Sequential)] struct PropVariant {
    internal ushort Type,Reserved1,Reserved2,Reserved3; internal IntPtr Value,Extra;
    internal const ushort Empty=0,Bool=11,Wide=31;
    internal static PropVariant FromBool(bool on) { PropVariant v=new PropVariant(); v.Type=Bool; v.Value=new IntPtr(on?0xFFFF:0); return v; }
    internal bool? AsBool() { return Type==Bool?(Value.ToInt64()&0xFFFF)!=0:(bool?)null; }
    internal string AsString() { return Type==Wide&&Value!=IntPtr.Zero?Marshal.PtrToStringUni(Value):null; }
}
