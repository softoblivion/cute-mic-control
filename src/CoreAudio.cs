// Undocumented interface: Windows has no public call that sets the default audio endpoint or writes an endpoint
// property through the audio service (a direct IPropertyStore write needs administrator rights). IPolicyConfig is the
// interface the Sound control panel uses; every slot is declared in vtable order, the unused ones as placeholders.
[ComImport, Guid("870AF99C-171D-4F9E-AF0D-E63DF40C2BC9")] class PolicyConfigClient { }
