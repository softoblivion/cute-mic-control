    internal static T Activate<T>(IMMDevice device) where T:class { Guid iid=typeof(T).GUID; object o; Check(device.Activate(ref iid,ClsctxAll,IntPtr.Zero,out o)); return (T)o; }
    internal static readonly PropertyKey FriendlyName=new PropertyKey(new Guid("A45C254E-DF1C-4EFD-8020-67D146A850E0"),14);
